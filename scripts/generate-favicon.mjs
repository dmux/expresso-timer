#!/usr/bin/env node
/**
 * Emits `src/app/icon.svg`, which Next's App Router picks up as the favicon.
 *
 * Its own 16×16 matrix rather than a scaled-down CUP_SPRITE: at favicon size the 45×32
 * mug turns to mush, so the artwork has to be redrawn for the grid it will actually be
 * seen on. Colours are copied from the light palette because a favicon cannot follow
 * the app's theme — a white mug with a dark outline reads on either browser chrome.
 *
 * Run with `pnpm gen:favicon` after editing ROWS.
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const SIZE = 16

const ROWS = [
  "................",
  "................",
  "..###########...",
  "..#CCCCCCCCC#...",
  "..#CLLLLLLLC#...",
  "..#CLLLLLLLC###.",
  "..#CLLLLLLLC#.#.",
  "..#CLLLLLLLC#.#.",
  "..#CLLLLLLLC#.#.",
  "..#CLLLLLLLC###.",
  "..#CLLLLLLLC#...",
  "...#CLLLLLC#....",
  "....#CLLLC#.....",
  ".....#CCC#......",
  "................",
  "................",
]

const COLOR = {
  "#": "#3a3532", // outline — darker than --px-ink, which is too soft at 16px
  C: "#f4f2ef", // ceramic
  L: "#8a6a55", // coffee
}

const ragged = ROWS.map((row, y) => [y, row.length]).filter(([, w]) => w !== SIZE)
if (ragged.length > 0 || ROWS.length !== SIZE) {
  console.error(`favicon matrix must be ${SIZE}×${SIZE}`, ragged)
  process.exit(1)
}

/** Horizontal runs collapse into one <rect>, which roughly halves the file. */
const rects = []
ROWS.forEach((row, y) => {
  let x = 0
  while (x < SIZE) {
    const char = row[x]
    if (char === ".") {
      x += 1
      continue
    }

    const fill = COLOR[char]
    if (!fill) {
      console.error(`unknown favicon char "${char}" at ${x},${y}`)
      process.exit(1)
    }

    let run = 1
    while (x + run < SIZE && row[x + run] === char) run += 1

    rects.push(`  <rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`)
    x += run
  }
})

const svg = [
  `<!-- Generated by scripts/generate-favicon.mjs — edit the matrix there, not here. -->`,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" shape-rendering="crispEdges">`,
  `  <title>Expresso Timer</title>`,
  ...rects,
  `</svg>`,
].join("\n")

const out = fileURLToPath(new URL("../src/app/icon.svg", import.meta.url))
writeFileSync(out, `${svg}\n`)

console.log(`✓ src/app/icon.svg (${rects.length} rects, ${svg.length} bytes)`)
