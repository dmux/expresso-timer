#!/usr/bin/env node
/**
 * Emits every app icon from one 16×16 matrix:
 *
 *   src/app/icon.svg       favicon — transparent, picked up by Next's file convention
 *   src/app/apple-icon.png iOS home screen (iOS ignores the manifest icons entirely)
 *   public/icon-192.png    Android home screen / install prompt
 *   public/icon-512.png    splash screen and store listings
 *   public/icon-mask.png   maskable — same art, inset far enough to survive any crop
 *
 * Its own matrix rather than a scaled-down MUG_SPRITE: at icon size the 45×33 cup turns
 * to mush, so the artwork is redrawn for the grid it will actually be seen on. Colours
 * are copied from the light palette because an installed icon cannot follow the app's
 * theme — a white cup with a dark outline reads on either home screen.
 *
 * The PNGs are written by hand (zlib is in Node; an image library is not) so the whole
 * icon set stays a `pnpm gen:icons` away from the matrix below, with no dependency and
 * no binary asset anybody has to redraw.
 *
 * Run with `pnpm gen:icons` after editing ROWS.
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { deflateSync } from "node:zlib"

const SIZE = 16

const ROWS = [
  "................",
  ".############...",
  ".#CCCCCCCCCC#...",
  ".#CLLLLLLLLC#...",
  ".#CLLLLLLLLC###.",
  ".#CLLLLLLLLC#.#.",
  ".#CLLLLLLLLC#.#.",
  ".#CLLLLLLLLC#.#.",
  ".#CLLLLLLLLC###.",
  "..#CLLLLLLC#....",
  "..#CLLLLLLC#....",
  "...#CLLLLC#.....",
  "....######......",
  "................",
  "..##########....",
  "................",
]

const COLOR = {
  "#": "#3a3532", // outline — darker than --px-ink, which is too soft at 16px
  C: "#f4f2ef", // ceramic
  L: "#8a6a55", // coffee
}

/** The page colour. Installed icons are composited on an unknown wallpaper, so they
 *  need an opaque background of their own — transparency would come out black on iOS. */
const BACKGROUND = "#f2e3cf"

const ragged = ROWS.map((row, y) => [y, row.length]).filter(([, w]) => w !== SIZE)
if (ragged.length > 0 || ROWS.length !== SIZE) {
  console.error(`icon matrix must be ${SIZE}×${SIZE}`, ragged)
  process.exit(1)
}

for (const [y, row] of ROWS.entries()) {
  for (const [x, char] of [...row].entries()) {
    if (char !== "." && !COLOR[char]) {
      console.error(`unknown icon char "${char}" at ${x},${y}`)
      process.exit(1)
    }
  }
}

/* --- svg ------------------------------------------------------------------ */

/** Horizontal runs collapse into one <rect>, which roughly halves the file. */
function toSvg() {
  const rects = []

  ROWS.forEach((row, y) => {
    let x = 0
    while (x < SIZE) {
      const char = row[x]
      if (char === ".") {
        x += 1
        continue
      }

      let run = 1
      while (x + run < SIZE && row[x + run] === char) run += 1

      rects.push(
        `  <rect x="${x}" y="${y}" width="${run}" height="1" fill="${COLOR[char]}"/>`
      )
      x += run
    }
  })

  return [
    `<!-- Generated by scripts/generate-icons.mjs — edit the matrix there, not here. -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" shape-rendering="crispEdges">`,
    `  <title>Expresso Timer</title>`,
    ...rects,
    `</svg>`,
  ].join("\n")
}

/* --- png ------------------------------------------------------------------ */

const CRC_TABLE = Int32Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c
})

function crc32(bytes) {
  let c = ~0
  for (const byte of bytes) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8)
  return ~c >>> 0
}

function chunk(type, data) {
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length)

  const body = Buffer.concat([Buffer.from(type, "latin1"), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))

  return Buffer.concat([length, body, crc])
}

/** 8-bit truecolour, no interlacing, every scanline unfiltered. */
function encodePng(size, pixels) {
  const stride = size * 3
  const raw = Buffer.alloc(size * (stride + 1))
  for (let y = 0; y < size; y += 1) {
    raw[y * (stride + 1)] = 0
    pixels.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride)
  }

  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 2 // colour type: truecolour

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ])
}

const rgb = (hex) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16))

/**
 * Nearest-neighbour by construction: the matrix is scaled by a whole number and centred,
 * so no edge ever lands on a fraction of a pixel. `fill` is how much of the canvas the
 * art is allowed to take — the rest is the margin a maskable crop or an iOS corner
 * radius eats into.
 */
function render(size, fill) {
  const scale = Math.floor((size * fill) / SIZE)
  const offset = Math.round((size - SIZE * scale) / 2)
  const pixels = Buffer.alloc(size * size * 3)

  const background = rgb(BACKGROUND)
  for (let i = 0; i < size * size; i += 1) {
    pixels.set(background, i * 3)
  }

  ROWS.forEach((row, matrixY) => {
    ;[...row].forEach((char, matrixX) => {
      if (char === ".") return
      const colour = rgb(COLOR[char])

      for (let dy = 0; dy < scale; dy += 1) {
        const y = offset + matrixY * scale + dy
        if (y < 0 || y >= size) continue

        for (let dx = 0; dx < scale; dx += 1) {
          const x = offset + matrixX * scale + dx
          if (x < 0 || x >= size) continue
          pixels.set(colour, (y * size + x) * 3)
        }
      }
    })
  })

  return encodePng(size, pixels)
}

/* --- output --------------------------------------------------------------- */

const at = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url))

const outputs = [
  ["src/app/icon.svg", `${toSvg()}\n`],
  // 0.8 for Apple: iOS only rounds the corners, so the art can run close to the edge.
  ["src/app/apple-icon.png", render(180, 0.8)],
  ["public/icon-192.png", render(192, 0.75)],
  ["public/icon-512.png", render(512, 0.75)],
  // Maskable icons are cropped to an unknown shape; the safe zone is the middle 80%,
  // and a circle inside that. Sitting at 53% clears it whatever the launcher does.
  ["public/icon-mask.png", render(512, 0.55)],
]

for (const [path, contents] of outputs) {
  writeFileSync(at(path), contents)
  console.log(`✓ ${path} (${contents.length} bytes)`)
}
